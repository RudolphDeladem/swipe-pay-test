// Embeds netlify/database/migrations/*.sql into server/migrations.gen.ts so the Vercel function
// never depends on reading SQL files at runtime. Run after adding a migration: npm run gen:migrations
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "netlify/database/migrations";
const entries = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((f) => `  [${JSON.stringify(f)}, ${JSON.stringify(readFileSync(`${dir}/${f}`, "utf8"))}],`);
writeFileSync("server/migrations.gen.ts",
  `// Generated by scripts/gen-migrations.mjs from ${dir}. Do not edit.\nexport const MIGRATIONS: [name: string, sql: string][] = [\n${entries.join("\n")}\n];\n`);
